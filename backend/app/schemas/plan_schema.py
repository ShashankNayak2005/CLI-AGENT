"""
Pydantic schemas and validators for multi-step AI agent planning and execution.
Enforces strict topological ordering, parameter validation, URL security, and operation whitelisting.
"""

from typing import Any, Dict, List, Literal, Optional
from pydantic import BaseModel, Field, field_validator, model_validator

from app.security.url_validator import URLSecurityValidator

OperationType = Literal["crawl_website", "summarize_crawl", "export_json"]
StepStatus = Literal["pending", "running", "completed", "failed", "skipped"]
PlanStatus = Literal["pending", "approved", "running", "completed", "failed", "cancelled"]

APPROVED_OPERATIONS = {"crawl_website", "summarize_crawl", "export_json"}


class PlanStep(BaseModel):
    """
    Individual step in a multi-step task execution plan.
    """
    step_id: int = Field(..., ge=1, le=10, description="Unique sequential step ID")
    operation: OperationType = Field(..., description="Approved operation type")
    description: str = Field(default="", description="Human-readable explanation of what this step will do")
    depends_on: List[int] = Field(default_factory=list, description="IDs of steps that must succeed before this step")
    parameters: Dict[str, Any] = Field(default_factory=dict, description="Validated parameters for the operation")
    status: StepStatus = Field(default="pending", description="Current step execution status")
    duration_seconds: float = Field(default=0.0, description="Execution duration of this step in seconds")
    output: Optional[Dict[str, Any]] = Field(default=None, description="Structured output payload produced by the step")
    error: Optional[str] = Field(default=None, description="Error diagnostics if step failed")

    @field_validator("operation")
    @classmethod
    def validate_operation(cls, op: str) -> str:
        if op not in APPROVED_OPERATIONS:
            raise ValueError(f"Disallowed operation '{op}'. Only {APPROVED_OPERATIONS} are permitted.")
        return op

    @field_validator("parameters")
    @classmethod
    def sanitize_parameters(cls, params: Dict[str, Any], info) -> Dict[str, Any]:
        """Validates parameter constraints based on operation type."""
        # Note: If filename is passed for export, prevent path traversal
        if "filename" in params:
            filename = str(params["filename"])
            if "/" in filename or "\\" in filename or ".." in filename:
                raise ValueError("Filename contains illegal path traversal characters.")
        return params


class TaskPlan(BaseModel):
    """
    Complete multi-step execution plan generated by Groq and validated by the backend.
    """
    plan_id: str = Field(..., description="Unique plan identifier")
    goal: str = Field(..., description="High-level objective summary")
    user_request: str = Field(..., description="Original user natural-language instruction")
    status: PlanStatus = Field(default="pending", description="Plan approval and execution state")
    steps: List[PlanStep] = Field(..., min_length=1, max_length=5, description="Ordered steps")
    created_at: str = Field(..., description="ISO 8601 creation timestamp")
    approved_at: Optional[str] = Field(default=None, description="ISO timestamp when user approved plan")
    completed_at: Optional[str] = Field(default=None, description="ISO timestamp when execution concluded")
    total_duration: float = Field(default=0.0, description="Total execution duration in seconds")
    error_message: Optional[str] = Field(default=None, description="Failure reason if plan failed")

    @model_validator(mode="after")
    def validate_plan_graph(self) -> "TaskPlan":
        """
        Validates step uniqueness, dependency existence, and prevents circular/self dependencies.
        Also validates that URL parameters in crawl_website pass SSRF validation.
        """
        step_ids = set()
        for step in self.steps:
            if step.step_id in step_ids:
                raise ValueError(f"Duplicate step_id '{step.step_id}' found in plan.")
            step_ids.add(step.step_id)

        for step in self.steps:
            # Self-dependency check
            if step.step_id in step.depends_on:
                raise ValueError(f"Step {step.step_id} cannot depend on itself.")

            # Dependency existence and forward-reference check
            for dep_id in step.depends_on:
                if dep_id not in step_ids:
                    raise ValueError(f"Step {step.step_id} references non-existent dependency step_id {dep_id}.")
                if dep_id >= step.step_id:
                    raise ValueError(
                        f"Step {step.step_id} has forward/circular dependency on step {dep_id}. "
                        "Dependencies must strictly precede the step."
                    )

            # Validate parameters for crawl_website
            if step.operation == "crawl_website":
                url = step.parameters.get("url")
                if not url:
                    raise ValueError(f"Step {step.step_id} (crawl_website) requires a 'url' parameter.")
                is_valid, reason, norm_url = URLSecurityValidator.validate_url(str(url))
                if not is_valid or not norm_url:
                    raise ValueError(f"Step {step.step_id} URL security validation failed: {reason}")
                step.parameters["url"] = norm_url

                # Clamp max_pages and max_depth
                step.parameters["max_pages"] = max(1, min(int(step.parameters.get("max_pages", 5)), 10))
                step.parameters["max_depth"] = max(0, min(int(step.parameters.get("max_depth", 1)), 2))

        return self


# API Request and Response models
class PlanGenerateRequest(BaseModel):
    """Payload to request Groq AI to generate a multi-step plan."""
    message: str = Field(..., min_length=1, max_length=4000, description="User instruction")


class PlanGenerateResponse(BaseModel):
    """Returned when a multi-step plan is generated and awaiting approval."""
    success: bool
    plan_id: str
    message: str
    plan: TaskPlan


class PlanExecuteRequest(BaseModel):
    """Approval payload sent when user confirms execution."""
    approved: bool = Field(default=True, description="Explicit approval confirmation")


class StepExecutionResult(BaseModel):
    """Trace of an individual step execution."""
    step_id: int
    operation: str
    status: StepStatus
    duration_seconds: float
    output: Optional[Dict[str, Any]] = None
    error: Optional[str] = None


class PlanExecuteResponse(BaseModel):
    """Response returned upon plan execution conclusion."""
    success: bool
    plan_id: str
    status: PlanStatus
    message: str
    total_duration: float
    steps: List[StepExecutionResult]
    final_result: Optional[Dict[str, Any]] = None

